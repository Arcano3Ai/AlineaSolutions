def generate_complete_hs():
    """Genera el dataset completo del Sistema Armonizado."""
    sections = []
    for sec in HS_STRUCTURE["sections"]:
        section_data = {
            "code": sec["code"],
            "title": sec["title"],
            "description": "Secci\u00f3n " + sec["code"] + ": " + sec["title"],
            "chapters": []
        }
        for ch_code, ch_title, headings in sec["chapters"]:
            chapter_data = {
                "code": ch_code,
                "title": ch_title,
                "description": "Cap\u00edtulo " + ch_code + ": " + ch_title,
                "headings": []
            }
            for h_code, h_title in headings.items():
                heading_data = {
                    "code": h_code,
                    "title": h_title,
                    "description": "Partida " + h_code + ": " + h_title,
                    "subheadings": []
                }
                subs = generate_subheadings(h_code, h_title)
                for sub_code, sub_title in subs:
                    heading_data["subheadings"].append({
                        "code": sub_code,
                        "title": sub_title,
                        "description": f"{sub_title} | Partida {h_code}: {h_title}"
                    })
                chapter_data["headings"].append(heading_data)
            section_data["chapters"].append(chapter_data)
        sections.append(section_data)
    return {"sections": sections}


def save_hs_data(filepath=None):
    if filepath is None:
        filepath = os.path.join(os.path.dirname(os.path.dirname(__file__)), "data", "hs_codes.json")
    data = generate_complete_hs()
    with open(filepath, "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=2)
    return data


